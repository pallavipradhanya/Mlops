"""Send realistic prediction traffic to the API so monitoring has data to analyse.

  python scripts/simulate_traffic.py --n 300                 # in-distribution traffic
  python scripts/simulate_traffic.py --n 300 --drift         # deliberately shifted traffic (demo of drift)

This is clearly synthetic demo traffic generated by the project's own generator; it is not hidden or faked
monitoring output. Every row goes through the real /api/predict/batch endpoint and is logged like any prediction.
"""
import argparse
import io
import sys
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from app.ml import data as D  # noqa: E402

p = argparse.ArgumentParser()
p.add_argument("--url", default="http://localhost:8000")
p.add_argument("--n", type=int, default=300)
p.add_argument("--drift", action="store_true", help="shift the feature distributions")
p.add_argument("--seed", type=int, default=123)
a = p.parse_args()

df = D.generate_synthetic(a.n, seed=a.seed, drift=a.drift, with_target=False)
buf = io.StringIO()
df.to_csv(buf, index=False)
r = requests.post(f"{a.url}/api/predict/batch", files={"file": ("traffic.csv", buf.getvalue())}, timeout=120)
if r.status_code != 200:
    sys.exit(f"Request failed ({r.status_code}): {r.text}")
print(r.json())
